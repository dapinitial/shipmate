#!/usr/bin/env bash
# deploy-card.sh — derive a project's deploy facts (remote, branch, DigitalOcean app) from the
# repo and the provider, and print or upsert a "## Deploy (shipmate)" block in its CLAUDE.md.
# Nothing here is hand-written: every line is read from git, .do/app.yaml, or doctl, so the
# block can't drift from reality without --check noticing.
#
# Usage: deploy-card.sh <project-dir> [--write] [--check]
#        deploy-card.sh --check-all [sites-root]
#   (no flag)    print the block for <project-dir>
#   --write      upsert the block (between shipmate markers) into <project-dir>/CLAUDE.md
#   --check      exit 1, with reasons, when the deploy facts are inconsistent:
#                  · .do/app.yaml names an app that does not exist on DigitalOcean
#                  · the live app deploys from a repo other than origin
#                  · .do/app.yaml's github.repo differs from origin
#                  · more than one remote and no remote.pushDefault
#                  · the default branch's upstream is not on origin
#   --check-all  run --check on every git repo under sites-root (default ~/Sites) that has a
#                .do/app.yaml; exit 1 if any fails
# Degrades gracefully: without doctl (or auth) the live checks are skipped and said so.
set -euo pipefail
case "${1:-}" in -h|--help|"") sed -n '2,20p' "$0"; exit 0;; esac

MARK_OPEN='<!-- shipmate:deploy-card — generated by skills/deploy/bin/deploy-card.sh; refresh with --write, verify with --check -->'
MARK_CLOSE='<!-- /shipmate:deploy-card -->'

# ---- helpers -------------------------------------------------------------------------------
slug_of() { # <git url> → owner/name (no .git); works for ssh, ssh-alias and https forms
  printf '%s' "${1:-}" | sed -E 's#/*$##; s#\.git$##; s#^.*[:/]([^/:]+/[^/]+)$#\1#'
}
have_doctl() { command -v doctl >/dev/null 2>&1 && doctl account get >/dev/null 2>&1; }

# ---- facts ---------------------------------------------------------------------------------
gather() { # <dir> — sets the FACT_* globals
  local dir="$1"
  FACT_NAME="$(basename "$dir")"
  FACT_ORIGIN="$(git -C "$dir" remote get-url origin 2>/dev/null || true)"
  FACT_SLUG="$(slug_of "$FACT_ORIGIN")"
  FACT_REMOTES="$(git -C "$dir" remote 2>/dev/null | tr '\n' ' ' | sed 's/ $//')"
  FACT_NREMOTES="$(printf '%s' "$FACT_REMOTES" | wc -w | tr -d ' ')"
  FACT_PUSHDEFAULT="$(git -C "$dir" config remote.pushDefault 2>/dev/null || true)"
  if git -C "$dir" show-ref --verify -q refs/heads/main; then FACT_BRANCH=main
  elif git -C "$dir" show-ref --verify -q refs/heads/master; then FACT_BRANCH=master
  else FACT_BRANCH="$(git -C "$dir" branch --show-current 2>/dev/null || echo main)"; fi
  FACT_UPSTREAM="$(git -C "$dir" rev-parse --abbrev-ref "$FACT_BRANCH@{upstream}" 2>/dev/null || true)"
  FACT_APP=""; FACT_APP_REPO=""; FACT_URL=""; FACT_LIVE=""; FACT_LIVE_REPO=""; FACT_ON_PUSH=""
  if [ -f "$dir/.do/app.yaml" ]; then
    FACT_APP="$(sed -nE 's/^name:[[:space:]]*//p' "$dir/.do/app.yaml" | head -1)"
    FACT_APP_REPO="$(sed -nE 's/^[[:space:]]*repo:[[:space:]]*//p' "$dir/.do/app.yaml" | head -1)"
  fi
  FACT_VERCEL=""; [ -d "$dir/.vercel" ] && FACT_VERCEL=yes
  if [ -n "$FACT_APP" ] && have_doctl; then
    local row id
    row="$(doctl apps list --format ID,Spec.Name,DefaultIngress --no-header 2>/dev/null \
            | awk -v n="$FACT_APP" '$2==n{print; exit}')"
    if [ -n "$row" ]; then
      FACT_LIVE=yes; id="$(printf '%s' "$row" | awk '{print $1}')"
      FACT_URL="$(printf '%s' "$row" | awk '{print $3}')"
      local spec; spec="$(doctl apps spec get "$id" 2>/dev/null || true)"
      FACT_LIVE_REPO="$(printf '%s\n' "$spec" | sed -nE 's/^[[:space:]]*repo:[[:space:]]*//p' | head -1)"
      FACT_ON_PUSH="$(printf '%s\n' "$spec" | sed -nE 's/^[[:space:]]*deploy_on_push:[[:space:]]*//p' | head -1)"
    else
      FACT_LIVE=no
    fi
  elif [ -n "$FACT_APP" ]; then
    FACT_LIVE=unknown   # no doctl / not authed
  fi
}

# ---- the block -----------------------------------------------------------------------------
card() {
  printf '%s\n' "$MARK_OPEN"
  echo "## Deploy (shipmate)"
  if [ -n "$FACT_SLUG" ]; then
    local pub="."
    [ "$FACT_ON_PUSH" = true ] && pub=" — a push publishes (deploy_on_push)."
    echo "- Production = push to \`$FACT_BRANCH\` on \`origin\` (\`$FACT_SLUG\`)$pub"
  else
    echo "- No \`origin\` remote — nothing deploys from this checkout."
  fi
  echo '- Only push target: `origin`. After pushing, `git status -sb` must show no "ahead" before claiming a deploy.'
  if [ "$FACT_NREMOTES" -gt 1 ]; then
    local others; others="$(printf '%s' "$FACT_REMOTES" | tr ' ' '\n' | grep -v '^origin$' | tr '\n' ' ' | sed 's/ $//')"
    echo "- Other remotes (\`$others\`) are read-only mirrors; never push to them."
  fi
  if [ -n "$FACT_APP" ]; then
    case "$FACT_LIVE" in
      yes)     echo "- DigitalOcean app: \`$FACT_APP\` · $FACT_URL (named in \`.do/app.yaml\`)" ;;
      no)      echo "- DigitalOcean app: \`$FACT_APP\` named in \`.do/app.yaml\` — **no live app by that name** (stale spec; fix the name)" ;;
      unknown) echo "- DigitalOcean app: \`$FACT_APP\` (named in \`.do/app.yaml\`; live state not checked — doctl unavailable)" ;;
    esac
    echo "- Voice: \"roll back $FACT_NAME, confirm\" reverts to the previous deployment; \"status\" reports the phase."
  elif [ -n "$FACT_VERCEL" ]; then
    echo "- Vercel project (\`.vercel/\`); git integration deploys \`$FACT_BRANCH\`. No DigitalOcean spec."
  else
    echo "- No \`.do/app.yaml\` — shipmate's app verbs (status, rollback) are unavailable here; \`/deploy\` creates one."
  fi
  printf '%s\n' "$MARK_CLOSE"
}

# ---- drift check ---------------------------------------------------------------------------
check() { # prints reasons; returns 1 if any
  local bad=0
  if [ -n "$FACT_APP" ]; then
    case "$FACT_LIVE" in
      no)  echo "  ✗ .do/app.yaml names '$FACT_APP' but no DigitalOcean app has that name"; bad=1 ;;
      yes) if [ -n "$FACT_LIVE_REPO" ] && [ "$FACT_LIVE_REPO" != "$FACT_SLUG" ]; then
             echo "  ✗ app '$FACT_APP' deploys from '$FACT_LIVE_REPO' but origin is '$FACT_SLUG'"; bad=1; fi ;;
      unknown) echo "  • live app not verified (doctl unavailable)" ;;
    esac
    if [ -n "$FACT_APP_REPO" ] && [ "$FACT_APP_REPO" != "$FACT_SLUG" ]; then
      echo "  ✗ .do/app.yaml github.repo is '$FACT_APP_REPO' but origin is '$FACT_SLUG'"; bad=1
    fi
  fi
  if [ "$FACT_NREMOTES" -gt 1 ] && [ -z "$FACT_PUSHDEFAULT" ]; then
    echo "  ✗ $FACT_NREMOTES remotes ($FACT_REMOTES) and no remote.pushDefault — a plain push is ambiguous"; bad=1
  fi
  case "$FACT_UPSTREAM" in
    ""|origin/*) ;;
    *) echo "  ✗ upstream of $FACT_BRANCH is '$FACT_UPSTREAM', not origin"; bad=1 ;;
  esac
  return $bad
}

# ---- upsert into CLAUDE.md -----------------------------------------------------------------
write_card() { # <dir>
  local f="$1/CLAUDE.md" tmp; tmp="$(mktemp)"
  card > "$tmp.card"
  if [ -f "$f" ] && grep -q -F 'shipmate:deploy-card' "$f"; then
    awk -v cardfile="$tmp.card" '
      /<!-- shipmate:deploy-card/ { while ((getline l < cardfile) > 0) print l; skip=1; next }
      /<!-- \/shipmate:deploy-card -->/ { skip=0; next }
      !skip { print }' "$f" > "$tmp" && mv "$tmp" "$f"
  else
    { [ -f "$f" ] && cat "$f"; [ -f "$f" ] && [ -n "$(tail -c1 "$f")" ] && echo; [ -f "$f" ] && echo; cat "$tmp.card"; } > "$tmp" && mv "$tmp" "$f"
  fi
  rm -f "$tmp.card"
  echo "✓ $f — deploy card written"
}

# ---- main ----------------------------------------------------------------------------------
if [ "${1:-}" = "--check-all" ]; then
  root="${2:-${SHIPMATE_SITES_ROOT:-$HOME/Sites}}"; fails=0; n=0
  for d in "$root"/*/; do
    [ -d "$d/.git" ] && [ -f "$d/.do/app.yaml" ] || continue
    n=$((n+1)); gather "${d%/}"
    if out="$(check)"; then printf '  \033[32m✓\033[0m %s → %s\n' "$(basename "$d")" "${FACT_APP:-?}"
    else printf '  \033[31m✗\033[0m %s\n%s\n' "$(basename "$d")" "$out"; fails=$((fails+1)); fi
  done
  echo "$n repo(s) with a DigitalOcean spec, $fails with drift"
  [ "$fails" -eq 0 ]
  exit
fi

DIR="${1%/}"; [ -d "$DIR/.git" ] || { echo "✗ not a git repo: $DIR"; exit 1; }
DIR="$(cd "$DIR" && pwd)"; shift
gather "$DIR"
case "${1:-}" in
  --write) write_card "$DIR" ;;
  --check) if check; then echo "✓ $(basename "$DIR") — deploy facts consistent"; else exit 1; fi ;;
  "")      card ;;
  *) echo "✗ unknown flag: $1"; exit 1 ;;
esac
